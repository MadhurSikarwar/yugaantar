#!/usr/bin/env python3
"""One command that decides whether the repository is fit to merge (owner: c1).

    python scripts/check_all.py [--toolkit PATH] [--skip-tests] [--allow-missing-toolkit]

Checks, in order. Any failure makes the exit code nonzero:

  1. layout     one adapter at the repo root; the toolkit is not inside the repo
  2. static     runtime code has no eval/exec, pickle, shell=True, os.system,
                network or ML imports (AST scan, not grep)
  3. secrets    no private keys or long key-like blobs in the working tree
                AND in the whole Git history (PRD rule 3)
  4. rule 0     no AI co-author trailers or AI identities in any commit
  5. validator  the official toolkit validator exits 0
  6. tests      the whole pytest suite passes

Only the Python standard library is used, so this runs anywhere Python 3.12 does.
"""
from __future__ import annotations

import argparse
import ast
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RUNTIME_PATHS = [REPO / "t4", REPO / "team_app.py", REPO / "track4_service.py"]

FORBIDDEN_CALLS = {"eval", "exec", "compile", "__import__"}
FORBIDDEN_ATTR_CALLS = {("os", "system"), ("os", "popen"), ("os", "execv"), ("os", "execve"), ("os", "spawnl")}
FORBIDDEN_MODULES = {
    # unsafe deserialization / dynamic code
    "pickle", "cPickle", "marshal", "shelve", "dill", "cloudpickle",
    # processes and native code
    "subprocess", "ctypes",
    # network
    "socket", "ssl", "urllib", "urllib2", "urllib3", "http", "httpx", "requests", "aiohttp",
    "ftplib", "smtplib", "telnetlib", "xmlrpc", "websocket", "websockets",
    # AI / ML (PRD rule 1)
    "numpy", "scipy", "sklearn", "torch", "tensorflow", "keras", "jax", "transformers", "xgboost", "lightgbm", "openai", "anthropic",
}

SECRET_PATTERNS = {
    "PEM private key": re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    "secret_key literal": re.compile(r"[\"']secret_key[\"']\s*:\s*[\"'][A-Za-z0-9+/=]{200,}[\"']"),
    "long base64 blob": re.compile(r"[A-Za-z0-9+/]{1500,}={0,2}"),
    "bare 64-hex key line": re.compile(r"(?m)^[0-9a-f]{64}$"),
}

AI_NAMES = re.compile(r"claude|anthropic|chatgpt|gpt-|openai|copilot", re.IGNORECASE)
AI_TRAILER = re.compile(r"(?im)^\s*(co-authored-by|generated[- ]with|generated by)\b.*")

results: list[tuple[str, bool, str]] = []


def record(name: str, ok: bool, detail: str = "") -> None:
    results.append((name, ok, detail))
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + (f": {detail}" if detail else ""), flush=True)


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, errors="replace")


def python_files(paths: list[Path]) -> list[Path]:
    found: list[Path] = []
    for path in paths:
        if path.is_file():
            found.append(path)
        elif path.is_dir():
            found += sorted(p for p in path.rglob("*.py") if "__pycache__" not in p.parts)
    return found


# --- 1. layout ---------------------------------------------------------------------------------


def check_layout() -> None:
    problems = []
    adapters = [p.name for p in REPO.iterdir() if p.is_file() and re.fullmatch(r"track4_service\.(py|cjs|js|mjs)", p.name)]
    if adapters != ["track4_service.py"]:
        problems.append(f"expected exactly track4_service.py at the root, found {adapters}")
    if (REPO / "Track-4-Toolkit").exists() or (REPO / "validate.py").exists():
        problems.append("the toolkit must live outside the repository")
    record("layout", not problems, "; ".join(problems))


# --- 2. static scan -----------------------------------------------------------------------------


def scan_file(path: Path) -> list[str]:
    issues = []
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (SyntaxError, UnicodeDecodeError) as error:
        return [f"{path.relative_to(REPO)}: cannot parse ({type(error).__name__})"]
    where = path.relative_to(REPO).as_posix()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in FORBIDDEN_MODULES:
                    issues.append(f"{where}:{node.lineno} imports {alias.name}")
        elif isinstance(node, ast.ImportFrom) and node.module:
            if node.module.split(".")[0] in FORBIDDEN_MODULES:
                issues.append(f"{where}:{node.lineno} imports from {node.module}")
        elif isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id in FORBIDDEN_CALLS:
                issues.append(f"{where}:{node.lineno} calls {func.id}()")
            if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
                if (func.value.id, func.attr) in FORBIDDEN_ATTR_CALLS:
                    issues.append(f"{where}:{node.lineno} calls {func.value.id}.{func.attr}()")
            for keyword in node.keywords:
                if keyword.arg == "shell" and isinstance(keyword.value, ast.Constant) and keyword.value.value is True:
                    issues.append(f"{where}:{node.lineno} uses shell=True")
    return issues


def check_static() -> None:
    issues: list[str] = []
    for path in python_files(RUNTIME_PATHS):
        issues += scan_file(path)
    record("static scan (runtime code)", not issues, "; ".join(issues[:5]) + (" ..." if len(issues) > 5 else ""))


# --- 3. secrets ----------------------------------------------------------------------------------


def scan_text(label: str, text: str) -> list[str]:
    return [f"{label}: {name}" for name, pattern in SECRET_PATTERNS.items() if pattern.search(text)]


def check_secrets() -> None:
    problems: list[str] = []
    listed = git("ls-files", "-co", "--exclude-standard", "-z")
    for name in filter(None, listed.stdout.split("\0")):
        path = REPO / name
        if path.is_file() and path.stat().st_size < 5_000_000:
            try:
                text = path.read_text(encoding="utf-8")
            except (UnicodeDecodeError, OSError):
                continue
            problems += scan_text(f"tree:{name}", text)
    history = git("log", "--all", "-p", "--no-color", "--format=commit %H")
    if history.returncode == 0:
        current = "?"
        for chunk in re.split(r"(?m)^commit ([0-9a-f]{40})$", history.stdout):
            if re.fullmatch(r"[0-9a-f]{40}", chunk):
                current = chunk[:10]
            else:
                problems += scan_text(f"history:{current}", chunk)
    record("secret scan (tree + history)", not problems, "; ".join(sorted(set(problems))[:5]))


# --- 4. rule 0 ---------------------------------------------------------------------------------------


def check_rule_zero() -> None:
    problems = []
    log = git("log", "--all", "--format=%an%x1f%ae%x1f%cn%x1f%ce%x1f%B%x1e")
    for record_text in log.stdout.split("\x1e"):
        parts = record_text.strip("\n").split("\x1f")
        if len(parts) < 5:
            continue
        an, ae, cn, ce, body = parts[0], parts[1], parts[2], parts[3], "\x1f".join(parts[4:])
        if any(AI_NAMES.search(value) for value in (an, ae, cn, ce)):
            problems.append(f"AI identity in commit by {an}")
        if AI_TRAILER.search(body):
            problems.append("AI trailer in a commit message")
    record("rule 0 (no AI attribution in history)", not problems, "; ".join(sorted(set(problems))))


# --- 5. validator -----------------------------------------------------------------------------------------


def find_toolkit(explicit: str | None) -> Path | None:
    for candidate in (explicit, os.environ.get("TRACK4_TOOLKIT"), str(REPO.parent / "Track-4-Toolkit")):
        if candidate and (Path(candidate) / "validate.py").is_file():
            return Path(candidate)
    return None


def check_validator(toolkit: Path | None, allow_missing: bool) -> None:
    if toolkit is None:
        record("official validator", allow_missing, "toolkit not found" + (" (allowed)" if allow_missing else ""))
        return
    done = subprocess.run(
        [sys.executable, str(toolkit / "validate.py"), "--entry", str(REPO / "track4_service.py")],
        capture_output=True, text=True, timeout=300,
    )
    detail = "" if done.returncode == 0 else f"exit {done.returncode}: " + " | ".join(
        line for line in done.stdout.splitlines() if line.startswith("FAIL")
    )[:300]
    record("official validator (exit 0)", done.returncode == 0, detail)


# --- 6. tests --------------------------------------------------------------------------------------------------


def check_tests() -> None:
    done = subprocess.run([sys.executable, "-m", "pytest", "-p", "no:cacheprovider"], cwd=REPO, capture_output=True, text=True, timeout=1800)
    summary = [line for line in done.stdout.splitlines() if re.search(r"\b(passed|failed|error)", line)]
    record("pytest suite", done.returncode == 0, summary[-1].strip("= ") if summary else "no summary line")
    if done.returncode != 0:
        print(done.stdout[-3000:])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--toolkit", help="path to the official Track-4-Toolkit checkout")
    parser.add_argument("--skip-tests", action="store_true", help="skip the pytest run (for quick iterations)")
    parser.add_argument("--allow-missing-toolkit", action="store_true", help="do not fail if the toolkit is absent")
    args = parser.parse_args()

    check_layout()
    check_static()
    check_secrets()
    check_rule_zero()
    check_validator(find_toolkit(args.toolkit), args.allow_missing_toolkit)
    if not args.skip_tests:
        check_tests()

    failed = [name for name, ok, _ in results if not ok]
    print("\n" + ("ALL CHECKS PASSED" if not failed else f"FAILED: {', '.join(failed)}"))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
